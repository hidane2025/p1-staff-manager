def img(b: DocBuilder, name: str, caption: str = "", h: float = 92) -> None:
    p = IMG / f"{name}.png"
    b.need(h + 14)   # 見出しだけ前ページに残らないようにする
    if p.exists():
        b.image(p, max_w_mm=176, max_h_mm=h, caption=caption)
    else:
        b.callout("画像未生成", f"{name}.png が見つかりません", color=COLOR_PRIMARY)


def h2(b: DocBuilder, title: str, img_h: float = 0) -> None:
    """見出しの前に余白を入れる。

    img_h を渡すと「見出し＋直後の画像」が同じページに収まるかで改ページを判定する
    （見出しだけ前ページに取り残されるのを防ぐ）。
    """
    b.spacer(6)
    b.need(30 + (img_h + 16 if img_h else 0))
    b.h2(title)


def step(b: DocBuilder, n: int, title: str, body: str = "") -> None:
    """番号付きの手順見出し"""
    b.need(20)
    y = b.y
    r = 4.2 * mm
    b.c.setFillColor(COLOR_SECONDARY)
    b.c.circle(MARGIN_X + r, y - r + 1.5 * mm, r, fill=1, stroke=0)
    b.c.setFillColor(white)
    b.c.setFont(FONT_JP_BOLD, 11)
    b.c.drawCentredString(MARGIN_X + r, y - r - 0.4 * mm, str(n))
    b.c.setFillColor(COLOR_INK)
    b.c.setFont(FONT_JP_BOLD, 12)
    b.c.drawString(MARGIN_X + r * 2.8, y - r - 0.3 * mm, title)
    b.y -= r * 2 + 2 * mm
    if body:
        b.para(body, size=10)


